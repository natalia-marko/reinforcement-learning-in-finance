# Portfolio Environment (weekly)
# ---------------------------------

class WeeklyPortfolioEnv(gym.Env):
    """
    A reinforcement learning environment for weekly portfolio rebalancing.

    Observations consist of the concatenated technical features for all
    tickers at the current week.  Actions are vectors in a bounded
    continuous space; these are scaled and passed through a softmax to
    produce portfolio weights that lie on the simplex (long‑only and
    fully invested).  The reward for each step is a Sharpe‑like
    quantity: the next week's portfolio log return divided by a
    running volatility estimate, annualized via sqrt(52).  The
    volatility estimate is an exponentially weighted moving variance of
    past portfolio returns.

    Parameters
    ----------
    tech_df : pandas.DataFrame
        Long‑format DataFrame of normalized technical features (by date
        and ticker).
    logret_wide : pandas.DataFrame
        Wide DataFrame of weekly log returns (columns: tickers).
    tickers : list of str
        Ordered list of tickers for the environment.
    feat_cols : list of str
        List of feature column names used in the observation.
    rolling_vol_window : int, optional
        Window length (in weeks) for the volatility EMA.  A minimum of
        this many timesteps will be consumed before starting the
        environment.  Default is 12.
    vol_ema_alpha : float or None, optional
        If specified, this directly sets the smoothing factor for the
        EMA variance.  Otherwise, alpha = 2/(window+1).  Default is
        None.
    random_start : bool, optional
        If True, each episode will start at a random time index within
        the available dates (after the warmup period).  Otherwise, the
        episode starts at the earliest valid index.  Default is
        False.
    softmax_temperature : float, optional
        Scale factor applied to actions before the softmax operation.
        Larger values lead to more peaked (less uniform) weight
        distributions.  Default is SOFTMAX_TEMPERATURE.
    """

    metadata = {"render_modes": []}

    def __init__(
        self,
        tech_df,
        logret_wide,
        tickers,
        feat_cols,
        rolling_vol_window=12,
        vol_ema_alpha=None,
        random_start=False,
        softmax_temperature=SOFTMAX_TEMPERATURE,
    ):
        super().__init__()
        self.tech_df = tech_df
        self.logret_wide = logret_wide
        self.tickers = tickers
        self.feat_cols = feat_cols
        self.n_assets = len(tickers)
        self.n_features = len(feat_cols)
        self.random_start = random_start
        self.temperature = float(softmax_temperature)

        # Finite action space required by stable‑baselines3.  We use
        # [-1, 1] bounds, then scale by temperature and apply softmax.
        self.action_space = spaces.Box(
            low=-1.0,
            high=1.0,
            shape=(self.n_assets,),
            dtype=np.float32,
        )

        # Observation is a flat vector of features for all assets
        self.observation_space = spaces.Box(
            low=-np.inf,
            high=np.inf,
            shape=(self.n_assets * self.n_features,),
            dtype=np.float32,
        )

        # Date index for the environment
        self.dates = self.logret_wide.index.sort_values()

        # Rolling window for volatility estimate
        self.W = int(rolling_vol_window)
        self.alpha = float(vol_ema_alpha) if vol_ema_alpha is not None else (2.0 / (self.W + 1.0))

        # The earliest index from which we can start (need W steps for
        # the volatility warmup) and at least one future return
        self.start_idx = max(self.W, 1)

        # Internal state variables
        self._t = None
        self._weights = None
        self._ema_mean = 0.0
        self._ema_var = 0.0
        self._ema_initialized = False

    def _get_obs(self):
        """Return the current observation as a flat vector."""
        d = self.dates[self._t]
        X = feature_matrix_on_date(d, self.tech_df, self.tickers, self.feat_cols)
        return X.flatten()

    def _softmax(self, x):
        """
        Convert action vector to portfolio weights using softmax.
        A temperature scale is applied prior to softmax to control
        sharpness of the resulting distribution.
        """
        x = np.asarray(x, dtype=np.float32) * self.temperature
        x = x - np.max(x)  # numerical stability
        e = np.exp(x)
        return e / (e.sum() + 1e-12)

    def reset(self, seed=None, options=None):
        """Reset the environment state at the start of an episode."""
        super().reset(seed=seed)
        if self.random_start:
            # Choose a random starting index within the valid range
            self._t = np.random.randint(self.start_idx, len(self.dates) - 2)
        else:
            # Deterministic start at earliest valid index
            self._t = self.start_idx

        # Initialize with equal weights
        self._weights = np.ones(self.n_assets, dtype=np.float32) / self.n_assets
        self._ema_mean = 0.0
        self._ema_var = 0.0
        self._ema_initialized = False

        return self._get_obs(), {}

    def step(self, action):
        """
        Execute one rebalancing action and observe the reward.
        """
        # Convert unbounded action to portfolio weights
        action = np.asarray(action, dtype=np.float32).reshape(-1)
        w = self._softmax(action)
        self._weights = w

        # Check if a future return exists
        if self._t + 1 >= len(self.dates) - 1:
            return self._get_obs(), 0.0, True, False, {}

        next_date = self.dates[self._t + 1]
        r_vec = self.logret_wide.loc[next_date, self.tickers].values.astype(np.float32)
        port_log_r = float(np.dot(w, r_vec))

        # Update EMA of mean and variance of returns
        if not self._ema_initialized:
            self._ema_mean = port_log_r
            self._ema_var = 0.0
            self._ema_initialized = True
        else:
            delta = port_log_r - self._ema_mean
            self._ema_mean += self.alpha * delta
            self._ema_var = (1.0 - self.alpha) * (self._ema_var + self.alpha * delta * delta)

        running_vol = math.sqrt(max(self._ema_var, 1e-12))
        reward = (port_log_r / (running_vol + 1e-12)) * math.sqrt(52.0)

        # Advance time index
        self._t += 1
        terminated = self._t >= (len(self.dates) - 2)
        info = {"port_log_r": port_log_r, "running_vol": running_vol}
        return self._get_obs(), float(reward), terminated, False, info

    def run_full_pass(self, model):
        """
        Run an entire episode with the given model and return the
        out‑of‑sample Sharpe ratio (annualized).
        """
        obs, _ = self.reset()
        rets = []
        done = False
        while not done:
            action, _ = model.predict(obs, deterministic=True)
            obs, _, done, _, info = self.step(action)
            if "port_log_r" in info:
                rets.append(info["port_log_r"])
        rets = np.asarray(rets, dtype=np.float64)
        if rets.std() < 1e-12:
            return 0.0
        return float((rets.mean() / (rets.std() + 1e-12)) * math.sqrt(52.0))


# ---------------------------------
# Early stopping on validation
# ---------------------------------

class ValSharpeEarlyStop(BaseCallback):
    """
    Callback to perform early stopping based on validation Sharpe.

    At regular intervals defined by `eval_freq` environment steps, the
    model is evaluated on a separate validation environment.  If the
    best validation Sharpe does not improve for `patience` evaluations
    in a row, training is halted.  When an improvement is observed,
    the model is saved to `best_model_path` (if provided).
    """

    def __init__(self, val_env, eval_freq=10_000, patience=5, best_model_path=None, verbose=1):
        super().__init__(verbose)
        self.val_env = val_env
        self.eval_freq = int(eval_freq)
        self.patience = int(patience)
        self.best_model_path = Path(best_model_path) if best_model_path else None
        self.best_sharpe = -np.inf
        self.no_improve = 0

    def _on_step(self):
        # Only evaluate at specified intervals
        if self.eval_freq <= 0 or (self.n_calls % self.eval_freq) != 0:
            return True

        sharpe = self.val_env.run_full_pass(self.model)
        if self.verbose:
            print(f"[Eval] steps={self.num_timesteps:,}  val_sharpe={sharpe:.3f}  best={self.best_sharpe:.3f}")

        # Check for improvement
        if sharpe > self.best_sharpe + 1e-6:
            self.best_sharpe = sharpe
            self.no_improve = 0
            if self.best_model_path is not None:
                self.model.save(str(self.best_model_path))
                if self.verbose:
                    print(f"  ✓ New best saved -> {self.best_model_path}")
        else:
            self.no_improve += 1
            if self.no_improve >= self.patience:
                if self.verbose:
                    print(f"  ⛔ Early stopping (no improvement in {self.patience} evals).")
                return False
        return True


# ---------------------------------
# Training and evaluation pipeline
# ---------------------------------

def train_and_select(
    data_dir=DATA_DIR,
    algo=ALGO,
    total_steps=TOTAL_STEPS,
    eval_freq=EVAL_FREQ,
    patience=PATIENCE,
    rolling_vol_window=ROLLING_VOL_W,
    learning_rate=LEARNING_RATE,
    gamma=GAMMA,
    seed=SEED,
):
    """
    Train a reinforcement learning agent on the given data and return
    performance metrics.

    Parameters
    ----------
    data_dir : str or Path, optional
        Directory containing the processed data and metadata.  Defaults
        to the module constant DATA_DIR.
    algo : str, optional
        Which algorithm to use ("ppo" or "sac").  Defaults to
        ALGO.
    total_steps : int, optional
        Total number of training steps.  Defaults to TOTAL_STEPS.
    eval_freq : int, optional
        Number of steps between validation evaluations.  Defaults
        to EVAL_FREQ.
    patience : int, optional
        Number of evaluations with no improvement before stopping.
        Defaults to PATIENCE.
    rolling_vol_window : int, optional
        EMA window for volatility in the reward.  Defaults to
        ROLLING_VOL_W.
    learning_rate : float, optional
        Learning rate for the optimizer.  Defaults to
        LEARNING_RATE.
    gamma : float, optional
        Discount factor.  Defaults to GAMMA.
    seed : int, optional
        Random seed.  Defaults to SEED.

    Returns
    -------
    dict
        A dictionary containing the train, validation, and test Sharpe
        ratios and the path to the saved model.
    """
    # Set seeds for reproducibility
    th.manual_seed(seed)
    np.random.seed(seed)

    meta = load_metadata(data_dir)

    # Load splits
    tech_tr, ret_tr, tickers, feat_cols = load_split_frames(data_dir, "train", meta)
    tech_va, ret_va, _, _ = load_split_frames(data_dir, "val", meta)
    tech_te, ret_te, _, _ = load_split_frames(data_dir, "test", meta)

    # Create environments
    env_tr = WeeklyPortfolioEnv(
        tech_tr,
        ret_tr,
        tickers,
        feat_cols,
        rolling_vol_window=rolling_vol_window,
        softmax_temperature=SOFTMAX_TEMPERATURE,
    )
    env_va = WeeklyPortfolioEnv(
        tech_va,
        ret_va,
        tickers,
        feat_cols,
        rolling_vol_window=rolling_vol_window,
        softmax_temperature=SOFTMAX_TEMPERATURE,
    )
    env_te = WeeklyPortfolioEnv(
        tech_te,
        ret_te,
        tickers,
        feat_cols,
        rolling_vol_window=rolling_vol_window,
        softmax_temperature=SOFTMAX_TEMPERATURE,
    )

    vec_env = DummyVecEnv([lambda: env_tr])

    algo = str(algo).lower()
    if algo == "ppo":
        # Choose a batch_size that divides n_steps (2048) to avoid warnings
        model = PPO(
            "MlpPolicy",
            vec_env,
            learning_rate=learning_rate,
            gamma=gamma,
            seed=seed,
            verbose=1,
            policy_kwargs=dict(activation_fn=th.nn.ReLU, net_arch=[256, 256]),
            batch_size=512,
            n_steps=2048,
            gae_lambda=0.95,
            ent_coef=0.1,
            clip_range=0.2,
        )
    elif algo == "sac":
        model = SAC(
            "MlpPolicy",
            vec_env,
            learning_rate=learning_rate,
            gamma=gamma,
            seed=seed,
            verbose=1,
            policy_kwargs=dict(
                activation_fn=th.nn.ReLU,
                net_arch=dict(pi=[256, 256], qf=[256, 256])
            ),
            buffer_size=200_000,
            batch_size=1024,
            tau=0.02,
            train_freq=64,
            gradient_steps=64,
        )
    else:
        raise ValueError("algo must be 'ppo' or 'sac'")

    # Set up early stopping callback
    best_model_path = Path(data_dir) / f"best_{algo}.zip"
    cb = ValSharpeEarlyStop(
        val_env=env_va,
        eval_freq=eval_freq,
        patience=patience,
        best_model_path=best_model_path,
        verbose=1,
    )

    # Train
    model.learn(total_timesteps=int(total_steps), callback=cb)

    # Load best model if it was saved
    if best_model_path.exists():
        model = (PPO if algo == "ppo" else SAC).load(str(best_model_path), env=vec_env)

    # Evaluate
    tr_sh = env_tr.run_full_pass(model)
    va_sh = env_va.run_full_pass(model)
    te_sh = env_te.run_full_pass(model)

    print("\n=== Final Sharpe (annualized) ===")
    print(f"Train: {tr_sh:.3f}")
    print(f"Valid: {va_sh:.3f}")
    print(f" Test: {te_sh:.3f}")

    final_path = Path(data_dir) / f"final_{algo}.zip"
    model.save(str(final_path))
    print(f"\nSaved final model -> {final_path}")

    return {"train_sharpe": tr_sh, "val_sharpe": va_sh, "test_sharpe": te_sh, "path": str(final_path)}


