# Directory where the data and metadata are stored
DATA_DIR = "data"

# Algorithm to use: "ppo" or "sac"
ALGO = "ppo"

# Total number of environment steps to train
TOTAL_STEPS = 100_000

# Frequency (in steps) at which to evaluate the model on the
# validation set.  A larger value reduces validation overhead.
EVAL_FREQ = 10_000

# Number of evaluation rounds with no improvement before stopping
PATIENCE = 10

# EMA window (in weeks) used to compute the running volatility for the
# Sharpe‑like reward.  Typical values range from 12 to 26.
ROLLING_VOL_W = 12

# Learning rate for the optimizer
LEARNING_RATE = 3e-4

# Discount factor (gamma) for RL algorithms
GAMMA = 0.98

# Random seed for reproducibility
SEED = 42

# Softmax temperature: actions are scaled by this factor before
# softmax.  Higher values produce more concentrated weights.
SOFTMAX_TEMPERATURE = 6.0


