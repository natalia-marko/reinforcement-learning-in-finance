def load_metadata(data_dir):
    """Load metadata from a JSON file in the specified directory."""
    path = Path(data_dir) / "metadata.json"
    with open(path, "r") as f:
        return json.load(f)


def load_split_frames(data_dir, split, meta):
    """
    Load the normalized technical features and log returns for a given
    split ("train", "val", or "test").

    Parameters
    ----------
    data_dir : str or Path
        Base directory containing the data splits and metadata.
    split : str
        One of "train", "val", or "test".
    meta : dict
        Metadata dictionary loaded from metadata.json.

    Returns
    -------
    tech_df : pandas.DataFrame
        Long‑format normalized technical features with columns
        containing the features and a 'ticker' column.
    logret_wide : pandas.DataFrame
        Wide matrix of weekly log returns (index: date, columns:
        tickers).  This matrix is split‑scoped to avoid leakage.
    tickers : list of str
        Ordered list of tickers present in both technical and return
        data.  All processing will use this ordering.
    feat_cols : list of str
        Technical feature column names to feed into the model.  These
        correspond to the columns normalized during data preparation.
    """
    data_dir = Path(data_dir)

    # Load technical features
    tech_path = data_dir / split / "technical.csv"
    tech_df = pd.read_csv(tech_path, index_col=0, parse_dates=True)
    if "ticker" not in tech_df.columns:
        raise ValueError(f"{split}/technical.csv must contain a 'ticker' column.")

    # Select only the feature columns that were normalized
    feat_cols = meta.get("normalization", {}).get("technical", {}).get("columns", [])
    feat_cols = [c for c in feat_cols if c in tech_df.columns]

    # Load log returns (wide matrix) for this split
    ret_path = data_dir / split / "log_returns.csv"
    logret_wide = pd.read_csv(ret_path, index_col=0, parse_dates=True).sort_index()

    # Determine tickers that appear in both technical and return data
    tickers_feat = sorted(tech_df["ticker"].unique().tolist())
    tickers_ret = sorted(logret_wide.columns.tolist())
    tickers = [t for t in tickers_feat if t in tickers_ret]
    if not tickers:
        raise ValueError("No overlapping tickers between features and returns.")

    # Align both datasets to the intersection of dates
    common_idx = tech_df.index.intersection(logret_wide.index)
    tech_df = tech_df.loc[common_idx]
    logret_wide = logret_wide.loc[common_idx, tickers]

    return tech_df, logret_wide, tickers, feat_cols


def feature_matrix_on_date(date, tech_df, tickers, feat_cols):
    """
    Build a matrix of shape (n_assets, n_features) for a single date.

    This function extracts the rows corresponding to the given date from
    the technical features DataFrame, pivots them into a matrix
    indexed by ticker, and returns the feature values in the order
    specified by the 'tickers' list.  Missing values are filled with
    zero to ensure a well‑formed input matrix.

    Parameters
    ----------
    date : pandas.Timestamp
        The date for which to extract the feature matrix.
    tech_df : pandas.DataFrame
        Long‑format DataFrame of technical features.
    tickers : list of str
        Ordered list of tickers.
    feat_cols : list of str
        List of feature column names to include.

    Returns
    -------
    np.ndarray
        A 2D array of shape (n_assets, n_features) containing the
        feature values.  Any NaNs are replaced with zero.
    """
    rows = tech_df.loc[[date]]
    mat = (
        rows.set_index("ticker")[feat_cols]
        .reindex(tickers)
        .astype(np.float32)
        .fillna(0.0)
        .values
    )
    return mat


