def run(
    data_dir=DATA_DIR,
    algo=ALGO,
    total_steps=TOTAL_STEPS,
    eval_freq=EVAL_FREQ,
    patience=PATIENCE,
    rolling_vol_window=ROLLING_VOL_W,
    learning_rate=LEARNING_RATE,
    gamma=GAMMA,
    seed=SEED,
):
    """
    Run the training pipeline with the specified parameters.  This
    function is designed for interactive use in notebooks or scripts.

    Examples
    --------

    >>> import train_rl_weekly as trw
    >>> trw.run(data_dir="data", algo="ppo", total_steps=200_000)

    Parameters
    ----------
    data_dir : str or Path
        Base directory containing the processed data.
    algo : str
        "ppo" or "sac".
    total_steps : int
        Number of environment steps to train.
    eval_freq : int
        Evaluation frequency on the validation set.
    patience : int
        Number of evaluations without improvement before stopping.
    rolling_vol_window : int
        EMA window for volatility estimation.
    learning_rate : float
        Learning rate for the optimizer.
    gamma : float
        Discount factor.
    seed : int
        Random seed for reproducibility.

    Returns
    -------
    dict
        Dictionary containing train, validation, and test Sharpe
        ratios and the path to the saved model.
    """
    return train_and_select(
        data_dir=data_dir,
        algo=algo,
        total_steps=total_steps,
        eval_freq=eval_freq,
        patience=patience,
        rolling_vol_window=rolling_vol_window,
        learning_rate=learning_rate,
        gamma=gamma,
        seed=seed,
    )


