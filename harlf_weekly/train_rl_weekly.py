"""
Weekly Portfolio RL Training (Leak-Safe)
=======================================

This module provides a baseline reinforcement‑learning setup for weekly
portfolio rebalancing using only technical indicators as inputs.  It
implements two candidate algorithms—PPO and SAC—from the
stable‑baselines3 library.  The environment maps continuous actions to
long‑only portfolio weights via a softmax, and the reward is a
Sharpe‑like measure calculated from an exponentially weighted moving
variance of portfolio returns.  Early stopping is used to halt
training when the validation Sharpe no longer improves.

Key Features:
* **Gymnasium** is used instead of the deprecated gym library.
* **No type annotations** are included to avoid distractions.
* **No argparse** is used; instead, a `run()` function exposes the
  training interface for notebook or script use.
* **Finite action bounds** ensure compatibility with stable‑baselines3.
* **Technical features only**: macro data is ignored; feature names
  come from `metadata.json`.
* **Early stopping** monitors validation Sharpe at regular intervals.
* **Softmax temperature** allows control over weight sharpness.

To use this module interactively in a notebook:

```python
import train_rl_weekly as trw
trw.run(data_dir="data", algo="ppo", total_steps=300000)
```

Ensure your `data/` folder contains the preprocessed splits
(`train/technical.csv`, `train/log_returns.csv`, etc.) and a
corresponding `metadata.json` generated by your data preparation
pipeline.
"""

